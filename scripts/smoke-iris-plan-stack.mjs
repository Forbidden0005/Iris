#!/usr/bin/env node
/**
 * Smoke test for the Iris plan/task/evidence/review stack.
 *
 * Exercises lib/iris/plans.mjs end-to-end through its public helpers only:
 * create a plan, add a task, attach evidence, generate a draft review, then
 * reload everything from disk and assert it round-tripped correctly.
 *
 * This is a safety harness, not a product feature — no dashboard, no
 * server, no LLM, no dispatch/RT bus/engine adapter involvement.
 *
 * State dir: uses CREWSWARM_STATE_DIR as-is if the caller set it (real or
 * shared state — nothing here bulk-deletes in that case, only the plan id
 * and file path are printed). Otherwise creates a private temp directory
 * for this run only and removes it when done, so normal user state under
 * ~/.crewswarm is never touched by default.
 */
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const usingCallerStateDir = Boolean(process.env.CREWSWARM_STATE_DIR);
let tempStateDir = null;

if (!usingCallerStateDir) {
  tempStateDir = fs.mkdtempSync(path.join(os.tmpdir(), "iris-smoke-plan-stack-"));
  process.env.CREWSWARM_STATE_DIR = tempStateDir;
}

const { resetPaths, getStatePath } = await import("../lib/runtime/paths.mjs");
resetPaths();

const {
  createIrisPlan,
  addIrisPlanTask,
  addIrisPlanEvidence,
  generateIrisPlanReview,
  loadIrisPlan,
} = await import("../lib/iris/plans.mjs");

async function run() {
  const runId = Date.now();
  const planId = `iris-smoke-${runId}`;

  console.log(`[smoke-iris-plan-stack] runId=${runId}`);
  console.log(`[smoke-iris-plan-stack] stateDir=${getStatePath()} (${usingCallerStateDir ? "caller-provided" : "temp, will be removed"})`);

  console.log("[1/5] create plan...");
  const plan = createIrisPlan({
    id: planId,
    title: "Iris plan stack smoke test",
    userRequest: "Verify the plan/task/evidence/review stack round-trips through disk.",
    projectId: "iris-smoke",
  });
  assert.equal(plan.id, planId, "created plan id mismatch");
  console.log(`[ok] plan created (${plan.id})`);

  console.log("[2/5] add task...");
  const task = addIrisPlanTask(planId, {
    id: `${planId}-task`,
    agentId: "qa",
    title: "Smoke task",
    instructions: "Confirm the stack works end to end.",
  });
  console.log(`[ok] task added (${task.id})`);

  console.log("[3/5] add evidence linked to task...");
  const evidence = addIrisPlanEvidence(planId, {
    type: "note",
    taskId: task.id,
    title: "Smoke evidence",
    data: { text: "Generated by scripts/smoke-iris-plan-stack.mjs" },
  });
  console.log(`[ok] evidence added (${evidence.id})`);

  console.log("[4/5] generate draft review...");
  const review = generateIrisPlanReview(planId);
  console.log(`[ok] review generated (${review.id}, status=${review.status})`);

  console.log("[5/5] reload from disk and assert...");
  const reloaded = loadIrisPlan(planId);

  assert.ok(reloaded, "plan did not reload from disk");
  const reloadedTask = reloaded.tasks.find((t) => t.id === task.id);
  assert.ok(reloadedTask, "task missing after reload");
  const reloadedEvidence = reloaded.evidence.find((e) => e.id === evidence.id);
  assert.ok(reloadedEvidence, "evidence missing after reload");
  assert.ok(
    reloadedTask.evidenceIds.includes(evidence.id),
    "task.evidenceIds does not include the attached evidence id",
  );
  const reloadedReview = reloaded.reviews.find((r) => r.id === review.id);
  assert.ok(reloadedReview, "review missing after reload");
  assert.equal(reloadedReview.status, "draft", "generated review was not left in draft status");
  assert.ok(
    reloadedReview.taskIds.includes(task.id),
    "review.taskIds does not reference the task",
  );
  assert.ok(
    reloadedReview.evidenceIds.includes(evidence.id),
    "review.evidenceIds does not reference the evidence",
  );
  console.log("[ok] plan/task/evidence/review round-tripped through disk");

  console.log("");
  console.log("[smoke-iris-plan-stack] PASS");
  console.log(`  plan:     ${plan.id}`);
  console.log(`  task:     ${task.id}`);
  console.log(`  evidence: ${evidence.id}`);
  console.log(`  review:   ${review.id} (status=${review.status})`);
  if (usingCallerStateDir) {
    const planFile = path.join(getStatePath("iris-plans"), `${planId}.json`);
    console.log(`  stateDir: ${getStatePath()} (caller-provided, not cleaned up)`);
    console.log(`  planFile: ${planFile}`);
  } else {
    console.log(`  stateDir: ${tempStateDir} (temp, removed)`);
  }
}

run()
  .then(() => {
    cleanup();
  })
  .catch((err) => {
    console.error(`[smoke-iris-plan-stack] FAIL: ${err.message}`);
    cleanup();
    process.exit(1);
  });

function cleanup() {
  if (!usingCallerStateDir && tempStateDir) {
    try {
      fs.rmSync(tempStateDir, { recursive: true, force: true });
    } catch {
      // Best-effort — OS temp dirs get reaped eventually regardless.
    }
  }
}
